def find_language(query: str) -> tuple[str, str, str] | None:
    """按语言码或语言名查找。"""
    q = query.strip().upper()
    for code, name, country in KNOWN_LANGUAGES:
        if q == code.upper() or q == name.upper():
            return (code, name, country)
    return None


def format_language_line(code: str, name: str, country: str) -> str:
    """生成 CtvLanguage.ini 格式的行。"""
    return f"{code},      {name},           {country}"
